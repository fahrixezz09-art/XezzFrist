// LOGIN
// ==================================================

function showLogin() {

    showNotification(
        t("loginComing")
    );

}


// ==================================================
// CTA
// ==================================================

function focusSearch() {

    const input =
        document.getElementById(
            "searchInput"
        );

    if (!input) {
        return;
    }


    window.scrollTo({

        top: 0,

        behavior: "smooth"

    });


    setTimeout(() => {

        input.focus();

    }, 500);

}


// ==================================================
// NOTIFICATION
// ==================================================

function showNotification(message) {

    const notification =
        document.getElementById(
            "notification"
        );

    if (!notification) {
        return;
    }


    notification.textContent =
        message;


    notification.classList.add(
        "show"
    );


    clearTimeout(
        window.xezzNotificationTimer
    );


    window.xezzNotificationTimer =
        setTimeout(() => {

            notification.classList.remove(
                "show"
            );

        }, 3000);

}


// ==================================================
// HERO DYNAMIC TEXT
// ==================================================

const dynamicWord =
    document.querySelector(
        ".dynamic-word"
    );


// ==================================================
// PREPARE TEXT
// ==================================================

function prepareDynamicText() {

    if (!dynamicWord) {
        return;
    }


    const texts =
        dynamicTexts[currentLanguage];


    dynamicWord.textContent =
        texts[dynamicIndex];


    dynamicWord.style.transition =
        "none";

    dynamicWord.style.opacity =
        "1";

    dynamicWord.style.transform =
        "translateY(0)";

    dynamicWord.style.filter =
        "blur(0)";

}


// ==================================================
// RESET DYNAMIC TEXT
// ==================================================

function resetDynamicText() {

    if (!dynamicWord) {
        return;
    }


    dynamicIndex = 0;


    clearInterval(
        dynamicTimer
    );


    prepareDynamicText();


    dynamicTimer =
        setInterval(
            changeDynamicText,
            6500
        );

}


// ==================================================
// CHANGE HERO TEXT
// ==================================================

function changeDynamicText() {

    if (!dynamicWord) {
        return;
    }


    const texts =
        dynamicTexts[currentLanguage];


    dynamicWord.style.transition =
        "opacity 0.75s ease, transform 0.75s ease, filter 0.75s ease";

    dynamicWord.style.opacity =
        "0";

    dynamicWord.style.transform =
        "translateY(-8px)";

    dynamicWord.style.filter =
        "blur(4px)";


    setTimeout(() => {

        dynamicIndex++;


        if (
            dynamicIndex >=
            texts.length
        ) {

            dynamicIndex = 0;

        }


        dynamicWord.textContent =
            texts[dynamicIndex];


        dynamicWord.style.transition =
            "none";

        dynamicWord.style.opacity =
            "0";

        dynamicWord.style.transform =
            "translateY(10px)";

        dynamicWord.style.filter =
            "blur(4px)";


        void dynamicWord.offsetWidth;


        dynamicWord.style.transition =
            "opacity 0.85s cubic-bezier(.22,.61,.36,1), transform 0.85s cubic-bezier(.22,.61,.36,1), filter 0.85s cubic-bezier(.22,.61,.36,1)";

        dynamicWord.style.opacity =
            "1";

        dynamicWord.style.transform =
            "translateY(0)";

        dynamicWord.style.filter =
            "blur(0)";


    }, 800);

}


